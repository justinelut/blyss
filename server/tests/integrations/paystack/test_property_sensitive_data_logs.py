    @pytest.mark.asyncio
    async def test_webhook_signature_verification_logs_no_secrets(self, mock_logger):
        """
        Test that webhook signature verification does not log webhook secrets.
        """
        from polar.integrations.paystack.endpoints import PaystackWebhookEventGetter

        webhook_getter = PaystackWebhookEventGetter(settings.PAYSTACK_WEBHOOK_SECRET)

        # Test with invalid signature
        payload = b'{"event": "charge.success", "data": {"id": "test123"}}'
        invalid_signature = "invalid_signature"

        # Mock request
        mock_request = MagicMock()
        mock_request.body = AsyncMock(return_value=payload)
        mock_request.headers = {"x-paystack-signature": invalid_signature}

        with patch("polar.integrations.paystack.endpoints.log", mock_logger):
            with pytest.raises(Exception):  # Should raise HTTPException
                await webhook_getter(mock_request)

        # Check all log calls for sensitive data
        for call in (
            mock_logger.info.call_args_list
            + mock_logger.error.call_args_list
            + mock_logger.warning.call_args_list
        ):
            log_message = str(call)

            # Ensure webhook secret is not in logs
            assert settings.PAYSTACK_WEBHOOK_SECRET not in log_message

            # Ensure signature values are not fully logged (only boolean indicators)
            assert invalid_signature not in log_message

