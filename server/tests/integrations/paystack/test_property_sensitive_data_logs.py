class TestProperty32SensitiveDataNotInLogs:
    """
    Feature: paystack-integration, Property 32: Sensitive Data Not in Logs

    For any log entry or error message generated by the platform, it should not contain
    sensitive data such as API keys, webhook secrets, or full payment card numbers.
    """

    @pytest.fixture
    def mock_logger(self):
        """Mock logger to capture log entries."""
        logger = MagicMock()
        with patch("polar.integrations.paystack.service.log", logger):
            yield logger

    @pytest.fixture
    def paystack_service(self):
        """Create PaystackService instance for testing."""
        return PaystackService()

    @given(
        email=st.emails(),
        amount=st.integers(min_value=100, max_value=10000000),
        reference=st.text(min_size=10, max_size=50),
        subaccount=st.text(min_size=10, max_size=30),
    )
    @pytest.mark.asyncio
    async def test_transaction_initialization_logs_no_sensitive_data(
        self, mock_logger, paystack_service, email, amount, reference, subaccount
    ):
        """
        Test that transaction initialization logs do not contain sensitive API keys.
        """
        # Mock HTTP client response
        mock_response = MagicMock()
        mock_response.status_code = 200
        mock_response.json.return_value = {
            "status": True,
            "data": {
                "authorization_url": "https://checkout.paystack.com/test123",
                "reference": reference,
                "access_code": "test_access_code",
            },
        }

        with patch.object(paystack_service._client, "post", return_value=mock_response):
            await paystack_service.initialize_transaction(
                email=email,
                amount=amount,
                reference=reference,
                subaccount=subaccount,
            )

        # Check all log calls for sensitive data
        for call in mock_logger.info.call_args_list + mock_logger.error.call_args_list:
            log_message = str(call)

            # Ensure API key is not in logs
            assert settings.PAYSTACK_SECRET_KEY not in log_message
            assert "Bearer" not in log_message

            # Ensure no authorization headers are logged
            assert "Authorization" not in log_message

            # Check that only sanitized parameters are logged
            if "paystack.transaction.initialize" in log_message:
                # Should contain safe parameters
                assert email in log_message
                assert str(amount) in log_message
                assert reference in log_message
                assert subaccount in log_message

